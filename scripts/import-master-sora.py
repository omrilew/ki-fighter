#!/usr/bin/env python3
"""Import the Master Sora atlas from the artist's bundle.

Source: characters/master_sora.png + master_sora.json from
ki_fighter_all_characters_bundle.zip (64x96 cells, 8x8 grid, feet at 32,88).
The source is an illustrated draft with ~97k colours, so this reduces it to
one shared 24-colour palette (no dithering), keeps alpha hard, and removes
stray specks that are not connected to the figure or the staff.

Writes assets/campaign-cast/master-sora/master-sora.png and manifest.js.
Usage: python3 scripts/import-master-sora.py <bundle-dir>
"""
import json, sys
import numpy as np
from PIL import Image
from scipy import ndimage

src = sys.argv[1].rstrip('/') + '/characters/'
OUT = 'assets/campaign-cast/master-sora/'
COLORS = 24

img = Image.open(src + 'master_sora.png').convert('RGBA')
meta = json.load(open(src + 'master_sora.json'))
a = np.array(img)
alpha = a[..., 3] >= 128

# one palette for every frame, so the character's colours never shift
opaque = a[alpha][:, :3]
# k-means in a perceptual-ish space (Lab), so near-greys (hair, beard) stay neutral
from PIL import ImageCms
lab = np.array(ImageCms.applyTransform(Image.fromarray(opaque.reshape(-1, 1, 3)), ImageCms.buildTransformFromOpenProfiles(
    ImageCms.createProfile('sRGB'), ImageCms.createProfile('LAB'), 'RGB', 'LAB'))).reshape(-1, 3).astype(float)
rng = np.random.default_rng(1)
sample = lab[rng.choice(len(lab), min(40000, len(lab)), replace=False)]
centers = sample[rng.choice(len(sample), COLORS, replace=False)]
for _ in range(25):
    d = ((sample[:, None, :] - centers[None]) ** 2).sum(-1); lbl = d.argmin(1)
    for k in range(COLORS):
        if (lbl == k).any(): centers[k] = sample[lbl == k].mean(0)
# palette colour = mean sRGB of the pixels in each cluster
srgb = opaque[rng.choice(len(opaque), min(40000, len(opaque)), replace=False)] if False else None
d_all = ((lab[:, None, :] - centers[None]) ** 2).sum(-1).argmin(1)
pal = np.array([opaque[d_all == k].mean(0) if (d_all == k).any() else (0, 0, 0) for k in range(COLORS)]).round().astype(np.uint8)
# hair and beard: near-grey palette entries become neutral cool greys (the draft tints them green)
for k, (r, g, b) in enumerate(pal.astype(int)):
    mx, mn = max(r, g, b), min(r, g, b)
    if mx > 60 and (mx - mn) / mx < .22:
        m = (r + g + b) / 3
        pal[k] = (round(m * .98), round(m * .97), round(min(255, m * 1.06)))
pal_img = Image.new('P', (1, 1)); pal_img.putpalette(pal.reshape(-1).tolist() + [0] * (768 - COLORS * 3))
q = Image.fromarray(a[..., :3]).quantize(palette=pal_img, dither=Image.Dither.NONE).convert('RGB')
rgb = np.array(q)

# per cell: drop specks smaller than 8 px that are not part of the main body
cw, ch = meta['cell']
for r in range(a.shape[0] // ch):
    for c in range(a.shape[1] // cw):
        cell = alpha[r * ch:(r + 1) * ch, c * cw:(c + 1) * cw]
        lab, n = ndimage.label(cell, structure=np.ones((3, 3)))
        if n <= 1: continue
        sizes = ndimage.sum(cell, lab, range(1, n + 1))
        for i, sz in enumerate(sizes, 1):
            if sz < 8: cell[lab == i] = False

out = np.zeros_like(a)
out[..., :3] = np.where(alpha[..., None], rgb, 0)
out[..., 3] = np.where(alpha, 255, 0)
Image.fromarray(out).save(OUT + 'master-sora.png', optimize=True)

clips = {}
for name, clip in meta['clips'].items():
    clips[name] = {'frames': clip['frames'], 'fps': clip['fps'], 'loop': clip['loop']}
manifest = {'subject': 'master-sora', 'cell': [cw, ch], 'columns': meta['columns'], 'rows': meta['rows'],
            'feet': meta['anchor'], 'palette': COLORS, 'clips': clips,
            'source': 'ki_fighter_all_characters_bundle.zip (artist draft, palette-reduced)'}
open(OUT + 'manifest.js', 'w').write('// Generated by scripts/import-master-sora.py\nwindow.KiMasterSora=' + json.dumps(manifest) + ';\n')
print('wrote', OUT, 'colours', len(np.unique(out[out[..., 3] > 0][:, :3], axis=0)), 'clips', list(clips))
